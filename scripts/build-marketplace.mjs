#!/usr/bin/env node
// Generates the Jira-only Marketplace variant of ShipBrief from this repo.
//
//   node scripts/build-marketplace.mjs [output-dir]      (default: ../app-marketplace)
//
// Why a variant: an app that needs scopes for two Atlassian apps (Jira + Confluence) can only be
// listed on the Marketplace as a paid app, and an app submitted to the Marketplace can no longer
// be shared by installation link. The variant is a separate Forge app (its own app id) that:
//   - drops the search:confluence scope, so it installs on Jira only;
//   - sets CONFLUENCE_SEARCH = false, so the documentation check uses only the pages linked on
//     the work item, or reports "could not be checked".
// Everything else (panel, Rovo agent, MCP tools, scoring) is the same source.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// App id of the Marketplace variant ("ShipBrief", Jira-only). Override with SHIPBRIEF_MARKETPLACE_APP_ID
// if you registered your own copy.
export const MARKETPLACE_APP_ID = 'd35f95a5-06c8-44ec-83ed-c1832529bdaa';

const UUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/;

export function transformManifest(manifest, appId) {
  let out = manifest;
  const must = (from, to) => {
    if (typeof from === 'string' ? !out.includes(from) : !from.test(out)) {
      throw new Error(`build-marketplace: expected to find ${from} in manifest.yml`);
    }
    out = out.replace(from, to);
  };
  must(/^\s*- search:confluence\n/m, '');
  must(/(id: ari:cloud:ecosystem::app\/)[0-9a-f-]+/, `$1${appId}`);
  must(/^\s*# Registered .*\n/m, '  # Jira-only Marketplace variant. Generated by scripts/build-marketplace.mjs; do not edit by hand.\n');
  must(
    /Finds Confluence pages related to a Jira work item: pages linked from the issue\n\s+and pages that mention the issue key or match its summary\./,
    'Finds Confluence pages linked on a Jira work item (its web links). This build does\n        not search Confluence.'
  );
  if (/confluence/i.test(out.slice(out.indexOf('permissions:')))) {
    throw new Error('build-marketplace: a Confluence scope is still present');
  }
  return out;
}

export const VARIANT_JS = `// Generated by scripts/build-marketplace.mjs: Jira-only Marketplace build.
// No Confluence scope; the documentation check uses only the pages linked on the work item.
export const CONFLUENCE_SEARCH = false;
`;

const VARIANT_README = `# ShipBrief (Jira-only Marketplace build)

Generated from https://github.com/oatech-ignacio/shipbrief by \`scripts/build-marketplace.mjs\`.
Do not edit here; change the main repo and run the script again.

Differences from the main app:

- No \`search:confluence\` scope; installs on Jira only.
- The documentation check and \`find-related-docs\` report only the Confluence pages linked on the
  work item. If the links cannot be read the check is shown as "could not be checked".
- Separate Forge app id.
`;

function build(outDir) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const out = resolve(outDir || join(root, '..', 'app-marketplace'));
  if (out === root || root.startsWith(out + '/')) throw new Error('build-marketplace: refusing to write into the source tree');
  const appId = process.env.SHIPBRIEF_MARKETPLACE_APP_ID || MARKETPLACE_APP_ID;
  if (!UUID.test(appId)) throw new Error('build-marketplace: no Marketplace app id set');

  mkdirSync(out, { recursive: true });
  // Replace generated content only; node_modules and .forge in the output are left alone.
  for (const d of ['src', 'assets', 'test']) {
    rmSync(join(out, d), { recursive: true, force: true });
    cpSync(join(root, d), join(out, d), { recursive: true });
  }
  for (const f of ['package.json', 'package-lock.json', 'LICENSE', '.gitignore']) {
    if (existsSync(join(root, f))) cpSync(join(root, f), join(out, f));
  }
  // The variant test only makes sense in the main repo (it imports this script).
  rmSync(join(out, 'test', 'marketplace.test.mjs'), { force: true });
  writeFileSync(join(out, 'src', 'variant.js'), VARIANT_JS);
  writeFileSync(join(out, 'manifest.yml'), transformManifest(readFileSync(join(root, 'manifest.yml'), 'utf8'), appId));
  writeFileSync(join(out, 'README.md'), VARIANT_README);
  console.log(`Marketplace variant written to ${out} (app ${appId})`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  build(process.argv[2]);
}
